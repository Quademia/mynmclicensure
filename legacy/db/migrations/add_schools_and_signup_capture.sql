-- ============================================================
-- Add schools reference table (NMC-accredited, 141 seeded) +
-- signup-capture columns on users (school_id, school_other,
-- referral_source). Source: nmc.gov.gh/web/online-accreditation
-- ============================================================

CREATE TABLE IF NOT EXISTS schools (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  region      text NOT NULL,
  ownership   text,                 -- 'State' | 'Private'
  programmes  text[] DEFAULT '{}',  -- NMC programme codes (RGN, RM, ...)
  active      boolean NOT NULL DEFAULT true,
  created_at  timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE schools ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "schools_select" ON schools;
CREATE POLICY "schools_select" ON schools FOR SELECT USING (true);  -- public: needed on the (pre-auth) register page
GRANT SELECT ON schools TO anon, authenticated;

